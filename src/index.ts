/**
 * comfy-colab-cli
 * Headless CLI and AI agent skill to spin up ComfyUI on Google Colab,
 * execute API workflows, and auto-terminate GPU sessions.
 */

export interface ColabSessionConfig {
  gpuType?: 'T4' | 'A100' | 'V100';
  timeoutMinutes?: number;
  autoTerminate?: boolean;
  tunnelProvider?: 'cloudflared' | 'ngrok' | 'localtunnel';
}

export interface WorkflowJob {
  id: string;
  workflow: Record<string, unknown>;
  createdAt: number;
}

export interface SessionStatus {
  active: boolean;
  gpuType: string;
  uptimeSeconds: number;
  tunnelUrl: string | null;
}

export class ComfyColabClient {
  private readonly config: Required<ColabSessionConfig>;

  public constructor(config: ColabSessionConfig = {}) {
    this.config = {
      gpuType: config.gpuType ?? 'T4',
      timeoutMinutes: config.timeoutMinutes ?? 60,
      autoTerminate: config.autoTerminate ?? true,
      tunnelProvider: config.tunnelProvider ?? 'cloudflared',
    };
  }

  public getConfig(): Required<ColabSessionConfig> {
    return { ...this.config };
  }

  public generateColabNotebookScript(): string {
    const lines = [
      '# Auto-generated by comfy-colab-cli',
      `# GPU Target: ${this.config.gpuType}`,
      `# Auto-terminate: ${String(this.config.autoTerminate)}`,
      `# Tunnel Provider: ${this.config.tunnelProvider}`,
      '',
      '!git clone https://github.com/comfyanonymous/ComfyUI.git',
      '!pip install -r ComfyUI/requirements.txt',
      'import os',
      'print("[INFO] ComfyUI environment initialized")',
    ];
    return lines.join('\n');
  }

  public prepareWorkflow(workflow: Record<string, unknown>): WorkflowJob {
    if (!workflow || typeof workflow !== 'object' || Array.isArray(workflow)) {
      throw new TypeError('Workflow must be a valid non-array object');
    }

    const id = `job_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 8)}`;
    return {
      id,
      workflow: { ...workflow },
      createdAt: Date.now(),
    };
  }

  public parseStatus(rawStatus: {
    running?: boolean;
    gpu?: string;
    uptime?: number;
    url?: string;
  }): SessionStatus {
    return {
      active: Boolean(rawStatus.running),
      gpuType: rawStatus.gpu ?? this.config.gpuType,
      uptimeSeconds: rawStatus.uptime ?? 0,
      tunnelUrl: rawStatus.url ?? null,
    };
  }
}

export const VERSION = '0.1.0';
